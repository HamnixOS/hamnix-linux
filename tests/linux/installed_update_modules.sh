say "building the installed disk"
HAMLINUX_DISK_RC="$WORK/rc.phase1" HAMLINUX_DISK_EXTRA="$EXTRA" \
    nice -n 15 scripts/hamlinux_disk.sh "$DISK" 3G >"$WORK/build.log" 2>&1 || {
    echo "FAIL disk build"; tail -20 "$WORK/build.log"; exit 1; }
DISK_SUM_BEFORE="$(md5sum "$DISK" | cut -d' ' -f1)"

# =========================================================================
# 8. Boot it three times.
# =========================================================================
boot() {   # boot <logfile> <seconds>
    local log="$1" secs="$2"
    ( sleep 5 ) | HAMLINUX_DISK="$DISK" \
        timeout "$((secs + 25))" scripts/hamlinux_vm.sh disk --timeout "$secs" \
        >"$log" 2>&1 &
    VM=$!
    wait "$VM" 2>/dev/null
    VM=""
}
say "boot 1 of 3: the install that gives this machine its history (up to ${WAIT1}s)"
boot "$WORK/boot1.log" "$WAIT1"
say "boot 2 of 3: the machine as it stands, then the update (up to ${WAIT2}s)"
boot "$WORK/boot2.log" "$WAIT2"
say "boot 3 of 3: the same disk, and one modprobe (up to ${WAIT3}s)"
boot "$WORK/boot3.log" "$WAIT3"
DISK_SUM_AFTER="$(md5sum "$DISK" | cut -d' ' -f1)"

for n in 1 2 3; do
    echo
    echo "--------- boot $n transcript"
    grep -aE '^\[modupd\]|^rc\.boot:|^hpm:|^modprobe' "$WORK/boot$n.log" \
        | tr -d '\r' || tail -20 "$WORK/boot$n.log"
done
echo

# =========================================================================
# 9. The questions.
# =========================================================================
LOG=""
sect() {  # sect <phase> <name> -> the lines between the two markers
    sed -n "/\[modupd\] $1 $2-BEGIN/,/\[modupd\] $1 $2-END/p" "$LOG" | tr -d '\r'
}
has() {   # has <regex> in $LOG
    grep -aqE "$1" "$LOG"
}
inker() { # inker <blob> <module> -> 0 if the kernel's own list has it
    printf '%s\n' "$1" | grep -q "^${2//-/_} "
}

echo "--- boot 1: the machine gets its history"
LOG="$WORK/boot1.log"
has 'rc\.boot: hamnix-linux \(installed\)' \
    && ok "the installed root came online" \
    || bad "the installed root never came online"
has '\[modupd\] p1 dhcpc status: 0' && ok "dhcpc took a lease" || bad "dhcpc failed"
has '\[modupd\] p1 install status: 0' \
    && ok "the original install of $PKG exited 0" \
    || bad "the original install did not exit 0"
P1LIST="$(sect p1 LIST)"
if printf '%s\n' "$P1LIST" | grep -qE "$PKG[^0-9]*$OLDVER"; then
    ok "and the machine records $PKG at $OLDVER"
else
    bad "the machine does not record $PKG at $OLDVER (got: $(printf '%s' "$P1LIST" | tr '\n' '|'))"
fi
if printf '%s\n' "$P1LIST" | grep -q "$DRVPKG"; then
    bad "$DRVPKG is installed on the ORIGINAL machine -- it is supposed to model the channel that never had it"
else
    ok "$DRVPKG is NOT installed: this is a machine from before the modules were in any package"
fi
has "\[modupd\] p1 rm $MOD status: 0" \
    && ok "the $MOD driver was deleted from the disk" \
    || bad "the $MOD driver was not deleted"
P1TBL="$(sect p1 TABLE-AFTER)"
if printf '%s\n' "$P1TBL" | grep -qF "$LATE_LINE"; then
    ok "the driver-package lines for $LATE are in the machine's table: $LATE_LINE"
else
    bad "the $LATE line a driver hook appends is not in the machine's table"
fi

echo
echo "--- boot 2: THE MACHINE BEFORE THE UPDATE (the negatives)"
LOG="$WORK/boot2.log"
P2MODS="$(sect p2 MODULES-BEFORE)"
if [ "$(printf '%s\n' "$P2MODS" | grep -c '^[a-z_0-9]* [0-9]')" -lt 5 ]; then
    bad "/proc/modules listed fewer than 5 modules -- not a machine this can be measured on"
else
    ok "/proc/modules is readable and lists $(printf '%s\n' "$P2MODS" | grep -c '^[a-z_0-9]* [0-9]') modules"
fi
for m in "$MOD" "$DEPMOD_" "$LATE"; do
    if inker "$P2MODS" "$m"; then
        bad "$m was already in the kernel before the update -- this proves nothing"
    else
        ok "$m is not in the kernel before the update"
    fi
done
P2KOLS="$(sect p2 KOLS-BEFORE)"
if printf '%s\n' "$P2KOLS" | grep -q "$KO\$"; then
    bad "$KO is still on the disk before the update -- the deletion did not take"
else
    ok "$KO is NOT on the disk before the update ($(printf '%s\n' "$P2KOLS" | grep -i 'no such\|open failed\|cannot' | head -1))"
fi
P2MISS="$(sect p2 MISS)"
if printf '%s\n' "$P2MISS" | grep -q 'miss status: 0'; then
    bad "modprobe $MOD EXITED 0 on a machine that has no $MOD.ko -- success-shaped, having loaded nothing"
else
    ok "modprobe $MOD exits non-zero on the pre-update machine: $(printf '%s\n' "$P2MISS" | grep -iE 'modprobe:' | head -1)"
fi
P2LATE="$(sect p2 LATE)"
P2LATEMOD="$(sect p2 LATEMOD)"
if printf '%s\n' "$P2LATE" | grep -q 'late status: 0' && inker "$P2LATEMOD" "$LATE"; then
    ok "$LATE DOES load before the update -- the appended driver lines are live going in, so their survival is a real question"
else
    bad "$LATE does not load even before the update; the appended-line half would be vacuous"
fi

if [ "$NOUPD" = 1 ]; then
    echo "modupd: NOTE HAMLINUX_MODUPD_NOUPDATE=1 -- the update was deliberately not run"
    has '\[modupd\] p2 THE UPDATE WAS DELIBERATELY SKIPPED' \
        && ok "and the run says so out loud" || bad "the skip was not announced"
else
    echo
    echo "--- boot 2, continued: hpm update, no flags, against $LIVE_BASE"
    has '\[modupd\] p2 refresh status: 0' \
        && ok "a bare 'hpm refresh' TRUSTS the real repository" \
        || bad "a bare 'hpm refresh' did not exit 0"
    # AND IT WENT TO THE RIGHT CHANNEL. `main` holds Hamnix NATIVE binaries;
    # `linux` holds this userland. A machine that installed hamnix-base used to
    # be rewritten to `main` by the hpm package's own copy of
    # /etc/hpm/channels, and every refresh afterwards died on a 404 for
    # https://255.one/main/index.json.sig -- the machine cut off from its own
    # repository by the act of installing from it.
    has "hpm: (fetching channel|refreshed index from) .*255\.one/linux" \
        && ok "and it went to the real repository's LINUX channel -- installing the flagship package did not rewrite this machine's subscription" \
        || bad "the refresh did not name 255.one/linux: $(grep -a 'fetching channel' "$LOG" | head -1)"
    has '\[modupd\] p2 update status: 0' \
        && ok "a bare 'hpm update' exited 0" || bad "'hpm update' did not exit 0"
    has "hpm: upgrading $PKG $OLDVER -> $LIVEVER" \
        && ok "hpm named the upgrade $PKG $OLDVER -> $LIVEVER" \
        || bad "hpm did not name the $PKG upgrade"
    # THE MECHANISM: a package that is NEW in the channel arriving because the
    # version being upgraded to declares it.
    P2LIST="$(sect p2 LIST)"
    if printf '%s\n' "$P2LIST" | grep -qE "$DRVPKG[^0-9]*$DRVVER"; then
        ok "THE UPDATE PULLED IN A PACKAGE THAT DID NOT EXIST ON THIS MACHINE'S CHANNEL: $DRVPKG $DRVVER is now installed"
    else
        bad "$DRVPKG is NOT installed after the update. 'hpm update' upgrades installed packages, and a brand-new one only arrives as a dependency; nothing pulled it. THE 1.0.13 MODULES REACH NO UPDATING MACHINE."
    fi
    # THE BYTES, which no index field can satisfy.
    A="$(grep -aA1 -F "[modupd] p2 md5 of $KO after the update:" "$LOG" | tail -1 | tr -d '\r')"
    if printf '%s' "$A" | grep -q "$LIVE_KO_MD5"; then
        ok "$MOD.ko on the disk is the byte-for-byte published one ($LIVE_KO_MD5)"
    else
        bad "$MOD.ko on the disk is not the published bytes (got: $A)"
    fi
    B="$(grep -aA1 -F "[modupd] p2 md5 of $KODEP after the update:" "$LOG" | tail -1 | tr -d '\r')"
    if printf '%s' "$B" | grep -q "$LIVE_KODEP_MD5"; then
        ok "$DEPMOD_.ko on the disk is the byte-for-byte published one ($LIVE_KODEP_MD5)"
    else
        bad "$DEPMOD_.ko on the disk is not the published bytes (got: $B)"
    fi
fi
has '\[modupd\] PHASE2 DONE' && ok "phase 2 reached the end" || bad "phase 2 did not finish"

echo
echo "--- boot 3: THE SAME DISK. CAN IT LOAD A MODULE?"
LOG="$WORK/boot3.log"
has 'rc\.boot: hamnix-linux \(installed\)' \
    && ok "the machine booted again" || bad "the machine did not boot again"
P3LIST="$(sect p3 LIST)"
if [ "$NOUPD" != 1 ]; then
    printf '%s\n' "$P3LIST" | grep -qE "$DRVPKG[^0-9]*$DRVVER" \
        && ok "the new package survived the reboot ($DRVPKG $DRVVER)" \
        || bad "$DRVPKG is not installed after the reboot"
fi
# CAN THIS MACHINE TAKE THE *NEXT* UPDATE? A machine that has taken one and
# lost its subscription is a machine that will never take another, and nothing
# on it would say so.
P3CHAN="$(sect p3 CHANNELS)"
if printf '%s\n' "$P3CHAN" | grep -qx 'linux'; then
    ok "after the update the machine is still subscribed to the linux channel -- it can take the NEXT update too"
elif printf '%s\n' "$P3CHAN" | grep -qx 'main'; then
    bad "THE UPDATE REWROTE THIS MACHINE'S SUBSCRIPTION TO 'main'. That channel serves Hamnix NATIVE binaries and has no index.json.sig, so every future 'hpm refresh' on this machine aborts with a 404 and it can never take another update. The hpm package on the live channel ships etc/hpm/channels (the native list) at /etc/hpm/channels; the image stages etc/hpm/channels.linux there. Fixed in scripts/hamlinux_packages.py on this branch -- the live channel still carries the broken file and must be republished."
else
    bad "the machine's /etc/hpm/channels names no channel this gate recognises: $(printf '%s' "$P3CHAN" | tr '\n' '|')"
fi

P3BEFORE="$(sect p3 MODULES-BEFORE)"
for m in "$MOD" "$DEPMOD_" "$LATE"; do
    if inker "$P3BEFORE" "$m"; then
        bad "$m is in the kernel BEFORE modprobe runs -- something else loaded it and this proves nothing"
    else
        ok "$m is not in the kernel before modprobe runs on the updated machine"
    fi
done

# ===== QUESTION 1: THE MODULES ARRIVED AND THE NAME RESOLVES =====
P3LOAD="$(sect p3 LOAD)"
P3AFTER="$(sect p3 MODULES-AFTER)"
LORDER="$(printf '%s\n' "$P3LOAD" | sed -n 's/^modprobe: loaded \([a-z_0-9]*\) .*/\1/p' | tr '\n' ' ')"
say "modprobe $MOD loaded, in order: ${LORDER:-nothing}"
case "$LORDER" in
    "$DEPMOD_ $MOD "*) ok "loaded leaf-first: $DEPMOD_, then $MOD" ;;
    *) bad "load order was '${LORDER:-nothing}', not '$DEPMOD_ $MOD'" ;;
esac
for m in "$DEPMOD_" "$MOD"; do
    if inker "$P3AFTER" "$m"; then
        ok "$m IS IN THE KERNEL'S OWN LIST after the update: $(printf '%s\n' "$P3AFTER" | grep "^${m//-/_} " | head -1)"
    else
        bad "$m is NOT in /proc/modules -- an updated machine still cannot load it"
    fi
done
if printf '%s\n' "$P3AFTER" | grep -qE "^$DEPMOD_ .*$MOD"; then
    ok "the kernel records $MOD as a USER of $DEPMOD_ -- the dependency edge is real: $(printf '%s\n' "$P3AFTER" | grep "^$DEPMOD_ ")"
else
    bad "$DEPMOD_'s used-by column does not name $MOD; the dependency is not what was loaded"
fi

# ===== QUESTION 2: THE APPENDED DRIVER LINES SURVIVED =====
P3LATE="$(sect p3 LATE)"
LORDER2="$(printf '%s\n' "$P3LATE" | sed -n 's/^modprobe: loaded \([a-z_0-9]*\) .*/\1/p' | tr '\n' ' ')"
say "modprobe $LATE loaded, in order: ${LORDER2:-nothing}"
if printf '%s\n' "$P3LATE" | grep -q 'late status: 0'; then
    ok "modprobe $LATE exits 0 on the updated machine"
else
    bad "modprobe $LATE FAILED after the update: the machine keeps 8021q.ko on disk and has lost the only line that lets modprobe name it -- the appended driver lines did not survive. $(printf '%s\n' "$P3LATE" | grep -i 'modprobe:' | head -1)"
fi
for m in garp stp mrp llc "$LATE"; do
    if inker "$P3AFTER" "$m"; then
        ok "$m IS IN THE KERNEL'S OWN LIST: $(printf '%s\n' "$P3AFTER" | grep "^${m//-/_} " | head -1)"
    else
        bad "$m is not in /proc/modules after modprobe $LATE"
    fi
done

# ===== QUESTION 3: PREPEND, NOT REPLACE =====
P3TBL="$(sect p3 TABLE-BEFORE)"
FIRSTV="$(printf '%s\n' "$P3TBL" | grep "^kernel/fs/fat/$MOD\.ko:" | head -1)"
if [ -z "$FIRSTV" ]; then
    bad "the machine's table has no $MOD line at all after the update"
elif printf '%s' "$FIRSTV" | grep -q "$STALE"; then
    bad "the FIRST $MOD line is still the machine's stale one ($FIRSTV) -- the shipped table did not go in front, so modprobe resolves through a path that is not there"
else
    ok "the FIRST $MOD line is the shipped one, not the machine's stale one: $FIRSTV"
fi
if printf '%s\n' "$P3TBL" | grep -qF "$STALE"; then
    ok "and the machine's stale line is STILL IN THE TABLE, shadowed -- the shipped lines won by ORDER, which is what makes an appended driver line survivable"
else
    bad "the machine's own line is GONE: the package replaced the table instead of prepending it. Every line a driver package appended went with it."
fi
if printf '%s\n' "$P3TBL" | grep -qF "$LATE_LINE"; then
    ok "the driver-package line for $LATE is still in the table after the update"
else
    bad "the driver-package line for $LATE is gone from the table"
fi
has '\[modupd\] PHASE3 DONE' && ok "phase 3 reached the end" || bad "phase 3 did not finish"

echo
if [ "$DISK_SUM_BEFORE" = "$DISK_SUM_AFTER" ]; then
    bad "the disk is byte-identical before and after three boots -- nothing persisted"
else
    ok "the disk changed ($DISK_SUM_BEFORE -> $DISK_SUM_AFTER)"
fi
echo
echo "(live $PKG $LIVEVER, $DRVPKG $DRVVER; installed-at $OLDVER; kernel $KVER)"
echo "(logs: $WORK/boot1.log $WORK/boot2.log $WORK/boot3.log)"
echo "$PASS passed, $FAIL failed"
[ "$FAIL" = 0 ] || exit 1
